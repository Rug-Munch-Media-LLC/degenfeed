#!/usr/bin/env bash
# ── DegenFeed Screenshot Placeholder Generator ──────────────────
# Generates placeholder screenshots for App Store and Play Store
# submission using ImageMagick.
#
# Usage: bash generate-placeholders.sh
# Requires: imagemagick (convert, magick)
# Output: ./placeholder/{device}/{page}.png

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
OUTPUT_DIR="${SCRIPT_DIR}/placeholder"
FONT="${FONT:-/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf}"

DEGEN_GREEN="#00ff41"
DEGEN_DARK="#030712"
DEGEN_GRAY="#1f2937"
DEGEN_LIGHTER="#374151"
ACCENT_NOSTR="#8e30eb"
ACCENT_FARCASTER="#8a63d2"
ACCENT_LENS="#abfe2c"
ACCENT_BLUESKY="#1185fe"
MAGICK=$(command -v magick 2>/dev/null || command -v convert 2>/dev/null)

if [ -z "$MAGICK" ]; then
    echo "❌ ImageMagick not found. Install it:"
    echo "  brew install imagemagick   # macOS"
    echo "  apt install imagemagick    # Linux"
    exit 1
fi

declare -A DEVICES=(
    ["iphone6.7"]="1290x2796"
    ["iphone6.5"]="1242x2688"
    ["iphone5.5"]="1242x2208"
    ["ipad12.9"]="2048x2732"
    ["phone"]="1080x2340"
    ["tablet7"]="1200x1920"
    ["tablet10"]="1600x2560"
)

declare -a PAGES=("feed" "post" "discover" "profile" "messages")

mkdir -p "$OUTPUT_DIR"

for device in "${!DEVICES[@]}"; do
    size="${DEVICES[$device]}"
    device_dir="${OUTPUT_DIR}/${device}"
    mkdir -p "$device_dir"

    for page in "${PAGES[@]}"; do
        # Skip iPad messages/profile — only feed + discover required
        if [[ "$device" == ipad* ]] && [[ "$page" =~ ^(post|profile|messages)$ ]]; then
            continue
        fi
        if [[ "$device" == tablet* ]] && [[ "$page" =~ ^(post|profile|messages)$ ]]; then
            continue
        fi

        filename="${device_dir}/degenfeed-${page}-${device}.png"
        echo "Generating: ${filename} (${size})"

        $MAGICK -size "$size" "xc:${DEGEN_DARK}" \
            -fill "$DEGEN_GRAY" -draw "rectangle 0,0 ${size%x*},80" \
            -fill "$DEGEN_LIGHTER" -draw "rectangle 0,$((${size#*x} - 100)) ${size%x*},${size#*x}" \
            -font "$FONT" \
            -fill white -pointsize "$((${size%x*} / 20))" \
            -gravity North -annotate +0+20 "DegenFeed — ${page^}" \
            -fill "$DEGEN_GREEN" -pointsize "$((${size%x*} / 35))" \
            -gravity North -annotate +0+$((80 + ${size%x*} / 12)) "${device}  •  ${size}" \
            -fill "$DEGEN_LIGHTER" -pointsize "$((${size%x*} / 40))" \
            -gravity Center -annotate +0+0 "Screenshot placeholder\n${page^} view\n\nReplace with actual render" \
            -fill "$ACCENT_NOSTR" -pointsize "$((${size%x*} / 50))" \
            -gravity South -annotate +0+$((-60)) "▲ Generated by DegenFeed screenshot tool" \
            -fill gray50 -pointsize "$((${size%x*} / 55))" \
            -gravity South -annotate +0+$((-30)) "app.degenfeed.xyz" \
            "$filename"
    done
done

echo ""
echo "✅ All placeholders generated in ${OUTPUT_DIR}"
echo ""
echo "Files created:"
find "$OUTPUT_DIR" -type f -name "*.png" | sort
