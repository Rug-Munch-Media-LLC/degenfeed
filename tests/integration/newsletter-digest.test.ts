describe('Newsletter Digest: Trending Topics', () => {
  it('extracts trending topics from computeTrendingTopics', () => {
    const posts = [
      makeDigestPost({
        id: 'n:tr1',
        protocol: 'nostr',
        text: 'Bitcoin at new highs',
        niches: ['bitcoin', 'crypto'],
        likes: 100,
        createdAt: Date.now() - 3600000,
      }),
      makeDigestPost({
        id: 'n:tr2',
        protocol: 'nostr',
        text: 'Ethereum staking surge',
        niches: ['ethereum', 'defi'],
        likes: 80,
        createdAt: Date.now() - 7200000,
      }),
      makeDigestPost({
        id: 'fc:tr1',
        protocol: 'farcaster',
        text: 'Solana ecosystem growing',
        niches: ['solana'],
        likes: 60,
        createdAt: Date.now() - 1800000,
      }),
    ];

    const topics = computeTrendingTopics(posts, Date.now(), 5, 86400000);
    expect(topics.length).toBeGreaterThanOrEqual(3);
    const topicNames = topics.map((t) => t.topic);
    expect(topicNames).toContain('bitcoin');
    expect(topicNames).toContain('ethereum');
    console.log('[PASS] Trending topics:', topicNames.join(', '));
  });
});
