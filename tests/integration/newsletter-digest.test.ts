// ─── Digest data types ─────────────────────────────────────────────────

interface DigestItem {
  postId: string;
  protocol: string;
  text: string;
  author: string;
  score: number;
  niches: string[];
  url?: string;
}

interface Digest {
  title: string;
  date: string;
  items: DigestItem[];
  protocolCount: number;
  totalPosts: number;
  trendingTopics: string[];
  html: string;
}

// ─── Digest helper functions ────────────────────────────────────────────

function buildDigestHtml(digest: Digest): string {
  const itemsHtml = digest.items
    .map(
      (item) => `
        <div class="digest-item">
          <div class="digest-item-header">
            <span class="protocol-badge protocol-${item.protocol}">${item.protocol}</span>
            <span class="author">${item.author}</span>
          </div>
          <div class="digest-item-content">${item.text.slice(0, 200)}${item.text.length > 200 ? '...' : ''}</div>
          <div class="digest-item-meta">
            <span>Score: ${item.score.toFixed(1)}</span>
            <span>Niches: ${item.niches.join(', ')}</span>
            <a href="${item.url}">Read more →</a>
          </div>
        </div>`,
    )
    .join('\n');

  const topicsHtml = digest.trendingTopics
    .map((t) => `<span class="trending-topic">#${t}</span>`)
    .join(' ');

  return `<!DOCTYPE html>
<html>
<head><title>${digest.title}</title></head>
<body>
  <h1>${digest.title}</h1>
  <p class="date">${new Date(digest.date).toLocaleDateString()}</p>
  <div class="digest-meta">
    <span>${digest.totalPosts} posts from ${digest.protocolCount} protocols</span>
    <div class="trending-topics">${topicsHtml}</div>
  </div>
  <div class="digest-items">${itemsHtml}</div>
  <div class="digest-footer">
    <p>Generated by DegenFeed Cross-Protocol Digest Engine</p>
  </div>
</body>
</html>`;
}

function extractTrendingTopics(posts: any[]): string[] {
  const counts = new Map<string, number>();
  for (const p of posts) {
    for (const n of p.niches ?? []) {
      counts.set(n, (counts.get(n) ?? 0) + 1);
    }
  }
  return Array.from(counts.entries())
    .sort((a, b) => b[1] - a[1])
    .slice(0, 5)
    .map(([topic]) => topic);
}

function generateDigest(
  posts: any[],
  options: { qualityThreshold?: number; allowedProtocols?: string[]; title?: string } = {},
): Digest {
  const threshold = options.qualityThreshold ?? 0;
  let filtered = posts;

  // Filter by quality threshold
  if (threshold > 0) {
    filtered = filtered.filter((p: any) => {
      const rawScore = p.qualityScore ?? 0;
      const computedScore =
        rawScore > 0
          ? rawScore
          : p.metrics.likes / Math.max(p.metrics.likes + p.metrics.reposts, 1);
      return computedScore >= threshold;
    });
  }

  // Filter by allowed protocols
  if (options.allowedProtocols && options.allowedProtocols.length > 0) {
    filtered = filtered.filter((p: any) => options.allowedProtocols?.includes(p.protocol));
  }

  filtered.sort((a: any, b: any) => {
    const scoreA = a.qualityScore ?? a.metrics.likes;
    const scoreB = b.qualityScore ?? b.metrics.likes;
    return scoreB - scoreA;
  });

  const protocols = new Set(filtered.map((p: any) => p.protocol));
  const items: DigestItem[] = filtered.map((p: any) => ({
    postId: p.id,
    protocol: p.protocol,
    text: p.text,
    author: p.author.displayName,
    score: p.qualityScore ?? p.metrics.likes,
    niches: p.niches,
    url: `https://degenfeed.xyz/post/${p.id}`,
  }));

  const html = buildDigestHtml({
    title: options.title ?? 'DegenFeed Daily Digest',
    date: new Date().toISOString(),
    items,
    protocolCount: protocols.size,
    totalPosts: items.length,
    trendingTopics: extractTrendingTopics(filtered),
  });

  return {
    title: options.title ?? 'DegenFeed Daily Digest',
    date: new Date().toISOString(),
    items,
    protocolCount: protocols.size,
    totalPosts: items.length,
    trendingTopics: extractTrendingTopics(filtered),
    html,
  };
}

function makeDigestPost(overrides: {
  id: string;
  protocol: string;
  text: string;
  authorDisplayName?: string;
  followerCount?: number;
  niches?: string[];
  createdAt?: number;
  likes?: number;
  reposts?: number;
  qualityScore?: number;
}) {
  const now = Date.now();
  return {
    id: overrides.id,
    protocol: overrides.protocol,
    author: {
      id: `${overrides.protocol}:author_${overrides.id}`,
      primary: { protocol: overrides.protocol, id: `author_${overrides.id}` },
      handles: {
        nostr: null,
        farcaster: null,
        lens: null,
        bluesky: null,
        mastodon: null,
        threads: null,
        rss: null,
      },
      displayName: overrides.authorDisplayName ?? `Author @${overrides.protocol}`,
      bio: '',
      avatarUrl: '',
      verified:
        overrides.followerCount && overrides.followerCount > 10000
          ? [{ protocol: overrides.protocol, badge: 'verified' }]
          : [],
      followerCount: overrides.followerCount ?? 1000,
      followingCount: 200,
      links: [],
      keys: {},
    },
    text: overrides.text,
    html: `<p>${overrides.text}</p>`,
    embeds: [],
    parentId: undefined,
    rootId: undefined,
    createdAt: overrides.createdAt ?? now,
    metrics: {
      likes: overrides.likes ?? 50,
      reposts: overrides.reposts ?? 10,
      replies: 5,
      quotes: 2,
    },
    engagement: {
      viewerLiked: false,
      viewerReposted: false,
      viewerBookmarked: false,
      raw: {
        likes: overrides.likes ?? 50,
        reposts: overrides.reposts ?? 10,
        replies: 5,
        quotes: 2,
      },
    },
    niches: overrides.niches ?? ['crypto'],
    raw: {},
    qualityScore: overrides.qualityScore,
  } as any;
}

// ─── SUITE 1: Multi-Protocol Digest ─────────────────────────────────────

describe('Newsletter Digest: Multi-Protocol Generation', () => {
  it('includes posts from Nostr, Farcaster, and RSS', () => {
    const posts = [
      makeDigestPost({
        id: 'nostr:n1',
        protocol: 'nostr',
        text: 'Bitcoin is the future of money and store of value.',
        likes: 100,
      }),
      makeDigestPost({
        id: 'farcaster:f1',
        protocol: 'farcaster',
        text: 'Ethereum L2 solutions are scaling the ecosystem.',
        likes: 80,
      }),
      makeDigestPost({
        id: 'rss:r1',
        protocol: 'rss',
        text: 'New DeFi protocol launches with innovative yield optimization.',
        likes: 60,
      }),
    ];

    const digest = generateDigest(posts);
    expect(digest.totalPosts).toBe(3);
    expect(digest.protocolCount).toBe(3);
    expect(digest.items.some((i) => i.protocol === 'nostr')).toBe(true);
    expect(digest.items.some((i) => i.protocol === 'farcaster')).toBe(true);
    expect(digest.items.some((i) => i.protocol === 'rss')).toBe(true);
    console.log(`[PASS] Digest: ${digest.totalPosts} posts from ${digest.protocolCount} protocols`);
  });

  it('generates correct metadata', () => {
    const posts = [makeDigestPost({ id: 'nostr:meta1', protocol: 'nostr', text: 'Test' })];
    const digest = generateDigest(posts, { title: 'DeFi Weekly' });
    expect(digest.title).toBe('DeFi Weekly');
    expect(digest.items).toHaveLength(1);
    console.log('[PASS] Digest metadata:', digest.title);
  });
});

