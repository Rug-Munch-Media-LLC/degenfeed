function getNextDateForDayAndHour(dayOfWeek: number, hourUTC: number): Date {
  const now = new Date();
  const currentDay = now.getUTCDay();
  let daysUntil = dayOfWeek - currentDay;
  if (daysUntil <= 0) daysUntil += 7; // Next week

  const result = new Date(now);
  result.setUTCDate(result.getUTCDate() + daysUntil);
  result.setUTCHours(hourUTC, 0, 0, 0);
  return result;
}

function calculateNextRecurrence(entry: QueueEntry): string {
  const lastDate = entry.scheduledAt ? new Date(entry.scheduledAt) : new Date();
  let next: Date;

  switch (entry.recurrence) {
    case 'daily':
      next = new Date(lastDate.getTime() + 86400_000);
      break;
    case 'weekly':
      next = new Date(lastDate.getTime() + 7 * 86400_000);
      break;
    case 'monthly':
      next = new Date(lastDate);
      next.setUTCMonth(next.getUTCMonth() + 1);
      break;
    case 'weekdays': {
      next = new Date(lastDate.getTime() + 86400_000);
      while (next.getUTCDay() === 0 || next.getUTCDay() === 6) {
        next = new Date(next.getTime() + 86400_000);
      }
      break;
    }
    default:
      next = new Date(lastDate.getTime() + 7 * 86400_000);
  }

  // Check recurrence end
  if (entry.recurrenceEnd && next > new Date(entry.recurrenceEnd)) {
    return lastDate.toISOString(); // Won't execute again after check
  }

  return next.toISOString();
}

function calculateNextEvergreenRepost(entry: QueueEntry): string {
  const lastRepost = entry.lastRepostedAt ? new Date(entry.lastRepostedAt) : new Date();
  let intervalDays: number;

  switch (entry.evergreenFrequency) {
    case 'every-7d':
      intervalDays = 7;
      break;
    case 'every-14d':
      intervalDays = 14;
      break;
    case 'every-30d':
      intervalDays = 30;
      break;
    case 'every-90d':
      intervalDays = 90;
      break;
    default:
      intervalDays = 30;
  }

  return new Date(lastRepost.getTime() + intervalDays * 86400_000).toISOString();
}

function getRecurringEntriesForDate(entries: QueueEntry[], date: Date): QueueEntry[] {
  const _dateStr = date.toISOString().split('T')[0];
  const dayOfWeek = date.getUTCDay();

  return entries.filter((e) => {
    if (!e.recurrence) return false;
    if (e.status !== 'scheduled' && e.status !== 'published') return false;

    switch (e.recurrence) {
      case 'daily':
        return true;
      case 'weekdays':
        return dayOfWeek !== 0 && dayOfWeek !== 6;
      case 'weekly':
        // Check if the original schedule day matches
        return checkDayOfWeekMatch(e.scheduledAt, dayOfWeek);
      case 'monthly':
        // Check if the day of month matches
        return checkDayOfMonthMatch(e.scheduledAt, date.getUTCDate());
      default:
        return false;
    }
  });
}

function checkDayOfWeekMatch(scheduledAt: string | null, dayOfWeek: number): boolean {
  if (!scheduledAt) return false;
  const scheduled = new Date(scheduledAt);
  return scheduled.getUTCDay() === dayOfWeek;
}

function checkDayOfMonthMatch(scheduledAt: string | null, dayOfMonth: number): boolean {
  if (!scheduledAt) return false;
  const scheduled = new Date(scheduledAt);
  return scheduled.getUTCDate() === dayOfMonth;
}
