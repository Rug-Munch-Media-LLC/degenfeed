/**
 * @degenfeed/api-worker — Premium Publishing Queue
 *
 * Buffer-style cross-posting engine for Premium subscribers.
 * Features:
 *   - Publishing queue (add, list, reorder, cancel)
 *   - Batch publish (CSV/spreadsheet import with schedule)
 *   - Recurring posts (daily, weekly, monthly)
 *   - Calendar view (all scheduled posts by date)
 *   - AI time optimization (suggest best posting times)
 *   - Auto-threading (split long posts into threads)
 *   - Content recycling (auto-repost top-performing content)
 *   - Evergreen posts (mark posts that auto-repost periodically)
 *
 * All routes are premium-gated via premium-gate.ts.
 * All storage uses the CACHE KV namespace with premium: prefix.
 */

