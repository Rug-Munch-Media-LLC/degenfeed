/**
 * @degenfeed/api-worker — Farcaster Frames v2 Manifest Builder
 *
 * Generates the manifest file at `/.well-known/farcaster.json` per
 * the Frames v2 / Mini Apps specification.
 *
 * The manifest declares metadata about the frame application and
 * includes an optional accountAssociation to verify domain ownership
 * via a JFS (JSON Farcaster Signature) signed by the developer's
 * Farcaster custody address.
 *
 * @see https://miniapps.farcaster.xyz/docs/specification
 * @see https://github.com/farcasterxyz/protocol/discussions/205
 */

// ─── Types ──────────────────────────────────────────────────────────────────

export interface AccountAssociation {
  header: string;
  payload: string;
  signature: string;
}

export interface FrameConfig {
  /** Manifest version. Required. */
  version: '1';
  /** App name. Required. Max 32 characters. */
  name: string;
  /** Default launch URL. Required. Max 512 characters. */
  homeUrl: string;
  /** Frame application icon URL. 200x200px, <1MB. */
  iconUrl: string;
  /** Default image for feed rendering. 3:2 ratio. */
  imageUrl: string;
  /** Default button title. Max 32 characters. */
  buttonTitle: string;
  /** Splash image URL. 200x200px, <1MB. */
  splashImageUrl?: string;
  /** Hex color for splash background. */
  splashBackgroundColor?: string;
  /** Webhook URL for frame events (notifications, add/remove). */
  webhookUrl?: string;
  /** Account association for domain verification. Optional. */
  accountAssociation?: AccountAssociation;
}

// ─── Manifest Builder ───────────────────────────────────────────────────────

/**
 * Build the Farcaster Frame manifest object.
 *
 * This JSON is served at `/.well-known/farcaster.json` on the frame domain.
 * Farcaster clients fetch it to verify domain ownership and get app metadata.
 *
 * @param customConfig - Partial config overrides
 * @param accountAssociation - Optional JFS signature for domain verification
 * @returns FrameConfig object ready to JSON-serialize
 */
export function buildFrameManifest(
  customConfig?: Partial<FrameConfig>,
  accountAssociation?: AccountAssociation,
): FrameConfig {
  const manifest: FrameConfig = {
    version: '1',
    name: customConfig?.name || 'DegenFeed',
    homeUrl: customConfig?.homeUrl || 'https://app.degenfeed.xyz',
    iconUrl:
      customConfig?.iconUrl ||
      'https://app.degenfeed.xyz/favicon.svg',
    imageUrl:
      customConfig?.imageUrl ||
      'https://app.degenfeed.xyz/og/frame-default.png',
    buttonTitle: customConfig?.buttonTitle || 'Open DegenFeed',
    splashImageUrl:
      customConfig?.splashImageUrl ||
      'https://app.degenfeed.xyz/splash.png',
    splashBackgroundColor: customConfig?.splashBackgroundColor || '#000000',
    webhookUrl:
      customConfig?.webhookUrl ||
      'https://api.degenfeed.xyz/api/webhook/farcaster-frame',
  };

  if (accountAssociation) {
    manifest.accountAssociation = accountAssociation;
  }

  return manifest;
}

